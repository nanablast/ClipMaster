import AppKit

enum ClipboardPasteboardTypes {
    // Mark only history replay. Newly captured screenshot OCR should still enter history.
    static let historyReplay = NSPasteboard.PasteboardType("com.clipmaster.app.history-replay")
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let gif = NSPasteboard.PasteboardType("com.compuserve.gif")
    static let jpeg = NSPasteboard.PasteboardType("public.jpeg")
    static let heic = NSPasteboard.PasteboardType("public.heic")
    static let webp = NSPasteboard.PasteboardType("org.webmproject.webp")
    static let supportedImageTypes: [NSPasteboard.PasteboardType] = [
        gif, .png, jpeg, heic, webp, .tiff
    ]
    static let ignored: Set<NSPasteboard.PasteboardType> = [
        historyReplay, concealed, transient, autoGenerated
    ]
}

struct ClipboardSnapshot {
    let capturedAt: Date
    let appSource: String?
    let rawImageData: Data?
    let fileURLs: [URL]
    let stringContent: String?
    let typeNames: [String]

    init(
        capturedAt: Date = Date(),
        appSource: String? = nil,
        rawImageData: Data? = nil,
        fileURLs: [URL] = [],
        stringContent: String? = nil,
        typeNames: [String] = []
    ) {
        self.capturedAt = capturedAt
        self.appSource = appSource
        self.rawImageData = rawImageData
        self.fileURLs = fileURLs
        self.stringContent = stringContent
        self.typeNames = typeNames
    }

    // Budget retained payload bytes, independently of the number of queued copies.
    var byteCount: Int {
        (rawImageData?.count ?? 0) + (stringContent?.utf8.count ?? 0)
            + fileURLs.reduce(0) { $0 + $1.absoluteString.utf8.count }
    }
}

enum ClipboardSnapshotReadResult {
    case captured(ClipboardSnapshot)
    case ignored
    case retry
}

/// Accessed on the main thread; snapshots own their data and can cross to the worker queue.
protocol ClipboardSnapshotReading: AnyObject {
    var changeCount: Int { get }
    func readSnapshot(expectedChangeCount: Int) -> ClipboardSnapshotReadResult
}

final class PasteboardSnapshotReader: ClipboardSnapshotReading {
    private let pasteboard: NSPasteboard
    private let sourceApplication: () -> String?
    private let now: () -> Date

    init(
        pasteboard: NSPasteboard = .general,
        sourceApplication: @escaping () -> String? = {
            NSWorkspace.shared.frontmostApplication?.localizedName
        },
        now: @escaping () -> Date = Date.init
    ) {
        self.pasteboard = pasteboard
        self.sourceApplication = sourceApplication
        self.now = now
    }

    var changeCount: Int { pasteboard.changeCount }

    func readSnapshot(expectedChangeCount: Int) -> ClipboardSnapshotReadResult {
        guard changeCount == expectedChangeCount else { return .retry }

        let capturedAt = now()
        let appSource = sourceApplication()
        let types = Set(pasteboard.types ?? [])
        // Check metadata before requesting any potentially sensitive/lazily supplied payload.
        if !types.isDisjoint(with: ClipboardPasteboardTypes.ignored)
            || pasteboard.pasteboardItems?.contains(where: {
                !Set($0.types).isDisjoint(with: ClipboardPasteboardTypes.ignored)
            }) == true {
            return changeCount == expectedChangeCount ? .ignored : .retry
        }

        var fileURLs: [URL] = []
        var rawImageData: Data?
        var stringContent: String?

        if types.contains(.fileURL) {
            // Finder also supplies a TIFF file icon. Never request it for file copies.
            fileURLs = pasteboard.readObjects(forClasses: [NSURL.self], options: [
                .urlReadingFileURLsOnly: true
            ]) as? [URL] ?? []
        } else {
            // Prefer animated GIF and compressed formats over synthesized TIFF.
            for imageType in ClipboardPasteboardTypes.supportedImageTypes where types.contains(imageType) {
                if let data = pasteboard.data(forType: imageType), !data.isEmpty {
                    rawImageData = data
                    break
                }
            }
            if types.contains(.string) {
                stringContent = pasteboard.string(forType: .string)
            }
        }

        guard changeCount == expectedChangeCount else { return .retry }
        guard !fileURLs.isEmpty || rawImageData?.isEmpty == false || stringContent?.isEmpty == false else {
            let supported = Set([.fileURL, .string] + ClipboardPasteboardTypes.supportedImageTypes)
            // A producer can declare ownership before its data becomes available.
            return types.isEmpty || !types.isDisjoint(with: supported) ? .retry : .ignored
        }

        return .captured(ClipboardSnapshot(
            capturedAt: capturedAt,
            appSource: appSource,
            rawImageData: rawImageData,
            fileURLs: fileURLs,
            stringContent: stringContent,
            typeNames: types.map(\.rawValue).sorted()
        ))
    }
}

struct ClipboardSnapshotBuffer {
    struct AppendResult {
        let accepted: Bool
        let droppedCount: Int
    }

    private let countLimit: Int
    private let byteLimit: Int
    private var snapshots: [ClipboardSnapshot] = []
    private(set) var byteCount = 0
    var count: Int { snapshots.count }

    init(
        countLimit: Int = Constants.clipboardSnapshotCountLimit,
        byteLimit: Int = Constants.clipboardSnapshotByteLimit
    ) {
        precondition(countLimit > 0 && byteLimit > 0)
        self.countLimit = countLimit
        self.byteLimit = byteLimit
    }

    mutating func append(_ snapshot: ClipboardSnapshot) -> AppendResult {
        let size = snapshot.byteCount
        guard size <= byteLimit else {
            // An oversized copy must not evict the entire existing backlog.
            return AppendResult(accepted: false, droppedCount: 0)
        }
        var dropped = 0
        while snapshots.count >= countLimit || byteCount > byteLimit - size {
            _ = popFirst()
            dropped += 1
        }
        snapshots.append(snapshot)
        byteCount += size
        return AppendResult(accepted: true, droppedCount: dropped)
    }

    mutating func popFirst() -> ClipboardSnapshot? {
        guard !snapshots.isEmpty else { return nil }
        let snapshot = snapshots.removeFirst()
        byteCount -= snapshot.byteCount
        return snapshot
    }

    mutating func removeAll() {
        snapshots.removeAll()
        byteCount = 0
    }
}
